#!/usr/bin/env python3
"""Copies the built-in skins' palettes from the skins mod into hooks/skin-palettes.ts.

Flightdeck cannot import another plugin's files, and the skins mod keeps its palettes in code,
not in state; so the table is copied here. Run again after updating skins:

    python3 scripts/sync-skin-palettes.py [path/to/skins/hooks/themes]
"""
import glob, json, os, re, sys

default = sorted(glob.glob(os.path.expanduser('~/.claude/plugins/cache/hellosverre-mods/skins/*/hooks/themes')))
src = sys.argv[1] if len(sys.argv) > 1 else (default[-1] if default else None)
if not src:
    sys.exit('skins themes folder not found; pass it as the first argument')

def block(text, key):
    m = re.search(key + r':\s*\{(.*?)\}', text, re.S)
    return dict(re.findall(r"(\w+):\s*'(#[0-9a-fA-F]{6})'", m.group(1))) if m else None

out = {}
for f in sorted(glob.glob(os.path.join(src, '*.ts'))):
    if f.endswith('index.ts'):
        continue
    text = open(f).read()
    name = re.search(r"name:\s*'([^']+)'", text).group(1)
    entry = {'dark': block(text, 'palette')}
    light = block(text, 'light')
    if light:
        entry['light'] = light
    out[name] = entry

version = os.path.basename(os.path.dirname(os.path.dirname(os.path.abspath(src))))
dest = os.path.join(os.path.dirname(__file__), '..', 'hooks', 'skin-palettes.ts')
with open(dest, 'w') as fh:
    fh.write('// Generated by scripts/sync-skin-palettes.py from the skins mod ' + version + '; do not edit by hand.\n')
    fh.write('// The built-in skins\' colours, by skin name: `dark`, and `light` where the skin has its own.\n')
    fh.write('export type SkinPalette = Readonly<Record<string, string>>\n\n')
    fh.write('export const SKIN_PALETTES: Readonly<Record<string, { dark: SkinPalette; light?: SkinPalette }>> = ')
    fh.write(json.dumps(out, indent=2).replace('"', "'"))
    fh.write('\n')
print(f'{len(out)} skins from {src}')
